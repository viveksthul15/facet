#!/usr/bin/env node
// Every number in the marketing material comes from here, and here reads only the benchmark
// results files. Change nothing by hand: rerun this and the graphics + copy follow.
//   node marketing/build-speed-data.mjs 0.1.2 0.2.0
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const RESULTS = path.join(HERE, '..', 'bench', 'results');
const [OLD, NEW] = [process.argv[2] || '0.1.2', process.argv[3] || '0.2.0'];
const load = (v) => JSON.parse(fs.readFileSync(path.join(RESULTS, `results-${v}.json`), 'utf8'));
const A = load(OLD), B = load(NEW);

const factor = (a, b) => a / b;
const fmtMs = (ms) => (ms >= 1000 ? `${(ms / 1000).toFixed(ms >= 10000 ? 0 : 1)} s` : `${Math.round(ms)} ms`);
const fmtX = (x) => (x >= 10 ? `${Math.round(x)}×` : `${x.toFixed(1)}×`);
const claim = (x) => (x >= 2 ? `${fmtX(x)} faster` : x >= 1.05 ? `${Math.round((1 - 1 / x) * 100)}% faster` : x > 0.95 ? 'same' : `${Math.round((1 / x - 1) * 100)}% slower`);

// One row per headline metric. `old`/`new` are medians in ms straight from the results files.
const rows = [
  {
    key: 'click', label: 'Every click in the panel', sub: 'Claude Desktop from the Microsoft Store, 3 profiles',
    old: A.suites.actions['typical/detect'].listIpcMs.median, new: B.suites.actions['typical/detect'].listIpcMs.median,
    path: 'suites.actions["typical/detect"].listIpcMs.median',
  },
  {
    key: 'cold', label: 'Start → profiles on screen', sub: '25 profiles, 3 old data folders',
    old: A.suites.cold['large/stub'].firstContentMs.median, new: B.suites.cold['large/stub'].firstContentMs.median,
    path: 'suites.cold["large/stub"].firstContentMs.median',
  },
  {
    key: 'export', label: 'Export a 50 MB session to zip', sub: '298 turns, subagents + tool results',
    old: A.suites.export['50MB'].exportMs.median, new: B.suites.export['50MB'].exportMs.median,
    path: 'suites.export["50MB"].exportMs.median',
  },
  {
    key: 'list', label: 'Open the session list', sub: '215 transcripts, 735 MB',
    old: A.suites.sessions.large.openSessionsViewMs.median, new: B.suites.sessions.large.openSessionsViewMs.median,
    path: 'suites.sessions.large.openSessionsViewMs.median',
  },
  {
    key: 'filter', label: 'Filter the list, per keystroke', sub: '215 sessions',
    old: A.suites.sessions.large.filterKeystrokeMs.median, new: B.suites.sessions.large.filterKeystrokeMs.median,
    path: 'suites.sessions.large.filterKeystrokeMs.median',
  },
  {
    key: 'rename', label: 'Rename a profile', sub: 'Store install, 3 profiles (two renames)',
    old: A.suites.actions['typical/detect'].renameMs.median, new: B.suites.actions['typical/detect'].renameMs.median,
    path: 'suites.actions["typical/detect"].renameMs.median',
  },
].map((r) => ({ ...r, x: factor(r.old, r.new), oldText: fmtMs(r.old), newText: fmtMs(r.new), claim: claim(factor(r.old, r.new)) }));

const slower = [];
const walk = (a, b, p) => {
  if (a && typeof a === 'object' && 'median' in a && b && 'median' in b) {
    if (b.median > a.median * 1.05 && b.median - a.median > 5) slower.push({ path: p, old: a.median, new: b.median });
    return;
  }
  if (a && typeof a === 'object' && b && typeof b === 'object') for (const k of Object.keys(a)) if (!k.startsWith('__')) walk(a[k], b[k], `${p}.${k}`);
};
walk(A.suites, B.suites, 'suites');

const data = {
  oldVersion: OLD, newVersion: NEW,
  machine: `${A.machine.cpu.replace(/ with Radeon Graphics/, '').replace(/\s+/g, ' ').trim()} laptop, ${A.machine.ramGB} GB RAM, NVMe SSD, ${A.machine.os.replace(/ Home Single Language/, '').replace(/ 10\.0\.\d+/, '')}`,
  machineShort: 'a Ryzen 5 laptop',
  measuredOn: B.suites.cold.__ranAt.slice(0, 10),
  method: `medians of ${B.method.coldStartRuns} runs on the packaged build, same machine and data for both versions`,
  power: { old: A.environment.cold.power, new: B.environment.cold.power },
  headline: rows.find((r) => r.key === 'export'),
  rows,
  // the same click with the classic installer (no Store lookup) — quoted next to the headline so it is never over-claimed
  classicClick: { old: A.suites.actions['typical/stub'].listIpcMs.median, new: B.suites.actions['typical/stub'].listIpcMs.median },
  footprint: {
    idleMemoryMB: { old: A.suites.memory.idle.workingSetMB, new: B.suites.memory.idle.workingSetMB },
    installerMB: { old: A.suites.sizes.installerMB, new: B.suites.sizes.installerMB },
    idleCpuPct: { old: A.suites.memory.idleCpuPctOfOneCore, new: B.suites.memory.idleCpuPctOfOneCore },
  },
  slower,
  sources: { old: `bench/results/results-${OLD}.json`, new: `bench/results/results-${NEW}.json` },
};
fs.writeFileSync(path.join(HERE, 'speed-data.json'), JSON.stringify(data, null, 2));
fs.writeFileSync(path.join(HERE, 'speed-data.js'), `// generated by marketing/build-speed-data.mjs — do not edit\nwindow.SPEED = ${JSON.stringify(data, null, 2)};\n`);
console.log(rows.map((r) => `${r.label}: ${r.oldText} → ${r.newText} (${r.claim})`).join('\n'));
if (slower.length) console.log('\nslower:', slower.map((s) => `${s.path} ${s.old}→${s.new}`).join('\n  '));
